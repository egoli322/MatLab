function C = farenh2cels(F)
% FARENH2CELS Converts Fahrenheit to Celsius.
%   C = farenh2cels(F) converts temperature F
%   from Fahrenheit to Celsius.
%
%   Input:
%       F - Temperature in Fahrenheit.
%
%   Output:
%       C - Temperature in Celsius.
C = (F - 32) * 5/9;
end


